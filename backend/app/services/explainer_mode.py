from app.sse import sse_response

OVERVIEW_INDEX = -1
DEFAULT_TARGET_WORDS_PER_SECTION = 220
DEFAULT_MAX_SECTIONS = 12
DEFAULT_MINI_QUIZ_QUESTIONS = 3

_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+(?=[A-ZÀ-ÖØ-öëÇ0-9])")


# --- sectioning (no LLM) ---------------------------------------------------------------------


@dataclass(frozen=True)
class SectionPlan:
    """One planned section: which chunks it covers and how to label/cite it."""

    index: int
    title: str
    source_reference: str
    page_start: int | None
    page_end: int | None
    line_start: int | None
    line_end: int | None
    chunk_ids: tuple[int, ...]


def _chunk_words(chunk: Chunk) -> int:
    return len(chunk.text.split())


def _reference_label(document: Document, first: Chunk, last: Chunk) -> str:
    if document.content_type == ContentType.CODE:
        name = first.source_name or "the code"
        if first.line_start is not None and last.line_end is not None:
            return f"{name}:{first.line_start}-{last.line_end}"
        return name
    kind = "Slide" if document.source_format == SourceFormat.PPTX else "Page"
    if first.page_start is not None and last.page_end is not None:
        if first.page_start == last.page_end:
            return f"{kind} {first.page_start}"
        return f"{kind}s {first.page_start}-{last.page_end}"
    return first.heading or "Document section"


def _section_title(chunks: list[Chunk], index: int) -> str:
    """The heading of the group's largest chunk, i.e. its dominant topic."""
    candidates = [chunk for chunk in chunks if chunk.heading]
    if not candidates:
        return f"Section {index + 1}"
    dominant = max(candidates, key=lambda chunk: len(chunk.text))
    return dominant.heading or f"Section {index + 1}"


def _group_key(document: Document, chunk: Chunk) -> str | None:
    """A boundary chunks must not cross when growing a section (code: the source file)."""
    return chunk.source_name if document.content_type == ContentType.CODE else None


def _group_chunks(
    document: Document, chunks: list[Chunk], *, target_words: int
) -> list[list[Chunk]]:
    groups: list[list[Chunk]] = []
    current: list[Chunk] = []
    current_words = 0
    current_key: str | None = None

    for chunk in chunks:
        key = _group_key(document, chunk)
        crosses_file_boundary = current and key != current_key
        if current and (current_words >= target_words or crosses_file_boundary):
            groups.append(current)
            current, current_words = [], 0
        current.append(chunk)
        current_words += _chunk_words(chunk)
        current_key = key

    if current:
        groups.append(current)
    return groups


def _merge_smallest_neighbors(groups: list[list[Chunk]], max_sections: int) -> list[list[Chunk]]:
    """Merge adjacent groups (smallest combined word count first) down to ``max_sections``.

    This may merge across a code file boundary as a last resort; capping the section count
    takes priority once a document is large enough to need it.
    """
    groups = list(groups)
    while len(groups) > max_sections:
        sizes = [sum(_chunk_words(chunk) for chunk in group) for group in groups]
        best = min(range(len(groups) - 1), key=lambda i: sizes[i] + sizes[i + 1])
        groups[best] = groups[best] + groups[best + 1]
        del groups[best + 1]
    return groups


def plan_sections(
    document: Document,
    *,
    target_words: int = DEFAULT_TARGET_WORDS_PER_SECTION,
    max_sections: int = DEFAULT_MAX_SECTIONS,
) -> list[SectionPlan]:
    """Group a document's chunks into playback sections of roughly ``target_words`` each."""
    chunks = list(document.chunks)
    if not chunks:
        raise AppError(400, "EMPTY_DOCUMENT")

    groups = _group_chunks(document, chunks, target_words=target_words)
    if len(groups) > max_sections:
        groups = _merge_smallest_neighbors(groups, max_sections)

    plans: list[SectionPlan] = []
    for index, group in enumerate(groups):
        first, last = group[0], group[-1]
        plans.append(
            SectionPlan(
                index=index,
                title=_section_title(group, index),
                source_reference=_reference_label(document, first, last),
                page_start=first.page_start,
                page_end=last.page_end if last.page_end is not None else first.page_end,
                line_start=first.line_start,
                line_end=last.line_end if last.line_end is not None else first.line_end,
                chunk_ids=tuple(chunk.id for chunk in group),
            )
        )
    return plans


# --- caption splitting -----------------------------------------------------------------------


def split_into_captions(text: str) -> list[str]:
    """Split a spoken script into sentence-sized caption segments (also used as TTS utterances)."""
    text = text.strip()
    if not text:
        return []
    pieces = [piece.strip() for piece in _SENTENCE_SPLIT_RE.split(text) if piece.strip()]
    return pieces or [text]


# --- schemas ---------------------------------------------------------------------------------


class ExplainerScriptResponse(BaseModel):
    """One spoken script: the overview (``section_index=-1``) or a numbered section."""

    section_index: int
    title: str
    text: str
    captions: list[str] = Field(default_factory=list)
    source_reference: str | None = None
    page_start: int | None = None
    page_end: int | None = None
    line_start: int | None = None
    line_end: int | None = None
    quiz: QuizSetResponse | None = None
    metadata: dict[str, object] = Field(default_factory=dict)

    async def stream_response(self) -> StreamingResponse:
        """Stream the JSON payload as SSE tokens."""

        async def iterator() -> AsyncIterator[str]:
            payload = self.model_dump_json(ensure_ascii=False)
            for start in range(0, len(payload), 32):
                yield payload[start : start + 32]

        return sse_response(iterator())


class SectionSummary(BaseModel):
    """Section metadata only (no script text yet), for the plan/timeline."""

    index: int
    title: str
    source_reference: str
    page_start: int | None = None
    page_end: int | None = None
    line_start: int | None = None
    line_end: int | None = None


class ExplainerPlanResponse(BaseModel):
    """The result of planning: the section list plus the eagerly generated overview script."""

    document_id: str
    sections: list[SectionSummary]
    overview: ExplainerScriptResponse


class _ScriptDraft(BaseModel):
    """Structured script requested from the model."""

    text: str


# --- generation --------------------------------------------------------------------------


def _coerce_level(value: str) -> Level:
    try:
        return Level(value)
    except ValueError as exc:  # pragma: no cover - validation on endpoint input
        raise AppError(422, "validation_error", details={"field": "level", "value": value}) from exc


def _coerce_language(value: str) -> Language:
    try:
        return Language(value)
    except ValueError as exc:  # pragma: no cover - validation on endpoint input
        raise AppError(
            422, "validation_error", details={"field": "language", "value": value}
        ) from exc


def _find_existing_script(
    session: Session | None,
    document: Document,
    *,
    section_index: int,
    language: Language,
    level: Level,
    simplified: bool,
) -> ExplainerScript | None:
    """Look up an already-generated script directly in the database (the cache "hit" check).

    A plain query, not the ``document.explainer_scripts`` relationship: with the app's
    ``expire_on_commit=False`` sessions, a relationship collection loaded once (as this lookup
    itself would do) never picks up a row committed later in the same session, which would
    make every call after the first look like a cache miss.
    """
    if session is None:
        return None
    return session.scalar(
        select(ExplainerScript).where(
            ExplainerScript.document_id == document.id,
            ExplainerScript.section_index == section_index,
            ExplainerScript.language == language,
            ExplainerScript.level == level,
            ExplainerScript.simplified == simplified,
        )
    )


def _to_response(
    record: ExplainerScript, *, quiz: QuizSetResponse | None, cached: bool
) -> ExplainerScriptResponse:
    return ExplainerScriptResponse(
        section_index=record.section_index,
        title=record.title,
        text=record.script,
        captions=list(record.captions or []),
        source_reference=record.source_reference,
        page_start=record.page_start,
        page_end=record.page_end,
        line_start=record.line_start,
        line_end=record.line_end,
        quiz=quiz,
        metadata={
            "document_id": record.document_id,
            "level": record.level.value,
            "language": record.language.value,
            "simplified": record.simplified,
            "prompt_version": record.prompt_version,
            "model": record.model,
            "cached": cached,
        },
    )


def _render_chunk_text(document: Document) -> str:
    if not document.chunks:
        raise AppError(400, "EMPTY_DOCUMENT")
    return "\n\n".join(
        f"[{_reference_label(document, chunk, chunk)}]\n{chunk.text.strip()}"
        for chunk in document.chunks
    )


def _render_section_chunk_text(document: Document, section: SectionPlan) -> str:
    chunk_by_id = {chunk.id: chunk for chunk in document.chunks}
    chunks = [chunk_by_id[chunk_id] for chunk_id in section.chunk_ids if chunk_id in chunk_by_id]
    if not chunks:
        raise AppError(400, "EMPTY_DOCUMENT")
    return "\n\n".join(
        f"[{_reference_label(document, chunk, chunk)}]\n{chunk.text.strip()}" for chunk in chunks
    )


async def _generate_script_text(
    *,
    document: Document,
    provider: LLMProvider,
    document_text: str,
    level: Level,
    language: Language,
    scope: str,
    duration_hint: str,
    transition_instruction: str,
    simplify_instruction: str,
) -> str:
    builder = PromptBuilder()
    prompt = builder.build(
        task=Task.EXPLAINER,
        content_type=document.content_type,
        level=level,
        language=language,
        document_text=document_text,
        task_params={
            "scope": scope,
            "duration_hint": duration_hint,
            "transition_instruction": transition_instruction,
            "simplify_instruction": simplify_instruction,
        },
    )
    draft = await provider.generate_json(prompt.user, _ScriptDraft, system=prompt.system)
    text = draft.text.strip()
    if not text:
        raise AppError(500, "internal_error")
    return text


async def generate_overview(
    *,
    document: Document,
    provider: LLMProvider,
    level: Level | str,
    language: Language | str,
    session: Session | None = None,
) -> ExplainerScriptResponse:
    """Generate (or replay) the whole-document spoken overview, the first thing played."""
    level = _coerce_level(level.value if isinstance(level, Level) else level)
    language = _coerce_language(language.value if isinstance(language, Language) else language)

    existing = _find_existing_script(
        session,
        document,
        section_index=OVERVIEW_INDEX,
        language=language,
        level=level,
        simplified=False,
    )
    if existing is not None:
        return _to_response(existing, quiz=None, cached=True)

    text = await _generate_script_text(
        document=document,
        provider=provider,
        document_text=_render_chunk_text(document),
        level=level,
        language=language,
        scope="an overview of the whole document",
        duration_hint="one to two minutes",
        transition_instruction=(
            "Start with a short, warm welcome and tell the learner briefly what they will learn."
        ),
        simplify_instruction="",
    )

    record = ExplainerScript(
        document_id=document.id,
        section_index=OVERVIEW_INDEX,
        title="Overview",
        language=language,
        level=level,
        simplified=False,
        script=text,
        captions=split_into_captions(text),
        model=provider.model,
        prompt_version=PROMPT_VERSION,
    )
    if session is not None:
        record = _save_script(session, record)
    return _to_response(record, quiz=None, cached=False)


def _save_script(session: Session, record: ExplainerScript) -> ExplainerScript:
    """Persist ``record``, or return the identical row a concurrent request already saved.

    The frontend can ask for the same script twice at once (for example a double-fired effect);
    the table's unique key would then make the second insert fail with a 500. Whoever loses the
    race simply reuses the winner's row, which is equivalent content for the same key.
    """
    session.add(record)
    try:
        session.commit()
    except IntegrityError:
        session.rollback()
        existing = session.scalar(
            select(ExplainerScript).where(
                ExplainerScript.document_id == record.document_id,
                ExplainerScript.section_index == record.section_index,
                ExplainerScript.language == record.language,
                ExplainerScript.level == record.level,
                ExplainerScript.simplified == record.simplified,
            )
        )
        if existing is None:
            raise
        return existing
    return record


async def generate_section_script(
    *,
    document: Document,
    provider: LLMProvider,
    cache: ContentCache,
    store: ChromaVectorStore,
    embedding_provider: EmbeddingProvider,
    section: SectionPlan,
    level: Level | str,
    language: Language | str,
    simplified: bool = False,
    mini_quiz_questions: int = DEFAULT_MINI_QUIZ_QUESTIONS,
    session: Session | None = None,
) -> ExplainerScriptResponse:
    """Generate (or replay) one section's spoken script plus its mini-quiz."""
    level = _coerce_level(level.value if isinstance(level, Level) else level)
    language = _coerce_language(language.value if isinstance(language, Language) else language)

    existing = _find_existing_script(
        session,
        document,
        section_index=section.index,
        language=language,
        level=level,
        simplified=simplified,
    )
    if existing is not None:
        quiz = _quiz_set_response(existing) if existing.quiz_set is not None else None
        return _to_response(existing, quiz=quiz, cached=True)

    is_first = section.index == 0
    text = await _generate_script_text(
        document=document,
        provider=provider,
        document_text=_render_section_chunk_text(document, section),
        level=level,
        language=language,
        scope=f'the section titled "{section.title}"',
        duration_hint="about one minute",
        transition_instruction=(
            "Start with a short welcome."
            if is_first
            else "Start with a brief, natural transition from the previous section, for example "
            '"Now let\'s look at...".'
        ),
        simplify_instruction=(
            "The learner found the previous version of this too hard: explain it even more "
            "simply, with more everyday analogies and smaller steps."
            if simplified
            else ""
        ),
    )

    quiz_response = await generate_quiz(
        document=document,
        provider=provider,
        cache=cache,
        level=level,
        language=language,
        num_questions=mini_quiz_questions,
        types=["multiple_choice"],
        topic=section.title,
        store=store,
        embedding_provider=embedding_provider,
        session=session,
    )

    record = ExplainerScript(
        document_id=document.id,
        section_index=section.index,
        title=section.title,
        source_reference=section.source_reference,
        page_start=section.page_start,
        page_end=section.page_end,
        line_start=section.line_start,
        line_end=section.line_end,
        language=language,
        level=level,
        simplified=simplified,
        script=text,
        captions=split_into_captions(text),
        quiz_set_id=quiz_response.quiz_set_id if session is not None else None,
        model=provider.model,
        prompt_version=PROMPT_VERSION,
    )
    if session is not None:
        record = _save_script(session, record)
    return _to_response(record, quiz=quiz_response, cached=False)


def _quiz_set_response(script: ExplainerScript) -> QuizSetResponse:
    """Rebuild the public quiz payload for an already-generated section's mini-quiz."""
    quiz_set = script.quiz_set
    assert quiz_set is not None  # noqa: S101 - guarded by the caller
    return QuizSetResponse(
        quiz_set_id=quiz_set.id,
        questions=[
            {
                "id": question.id,
                "kind": question.kind.value,
                "topic": question.topic,
                "difficulty": question.difficulty.value,
                "question": question.question,
                "options": question.options or [],
                "source_reference": question.source_reference,
            }
            for question in quiz_set.questions
        ],
        weak_topics=[],
        metadata={
            "document_id": quiz_set.document_id,
            "level": quiz_set.level.value,
            "language": quiz_set.language.value,
            "prompt_version": quiz_set.prompt_version,
            "model": quiz_set.model,
            "cached": True,
        },
    )


async def generate_plan(
    *,
    document: Document,
    provider: LLMProvider,
    level: Level | str,
    language: Language | str,
    target_words: int = DEFAULT_TARGET_WORDS_PER_SECTION,
    max_sections: int = DEFAULT_MAX_SECTIONS,
    session: Session | None = None,
) -> ExplainerPlanResponse:
    """Plan the sections and eagerly generate the overview script."""
    sections = plan_sections(document, target_words=target_words, max_sections=max_sections)
    overview = await generate_overview(
        document=document, provider=provider, level=level, language=language, session=session
    )
    return ExplainerPlanResponse(
        document_id=document.id,
        overview=overview,
        sections=[
            SectionSummary(
                index=section.index,
                title=section.title,
                source_reference=section.source_reference,
                page_start=section.page_start,
                page_end=section.page_end,
                line_start=section.line_start,
                line_end=section.line_end,
            )
            for section in sections
        ],
    )
