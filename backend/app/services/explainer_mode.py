"""Explainer Mode: deterministic sectioning plus spoken overview/section script generation.

Sectioning (grouping a document's chunks into ~1-minute sections) is a plain, deterministic
function of the document's chunks — no LLM call, so it is cheap enough to recompute on every
request rather than persist separately. Only the generated scripts (overview and per-section)
are cached, as rows in the ``explainer_scripts`` table: the unique constraint on
``(document_id, section_index, language, level, simplified)`` doubles as the cache lookup, the
same way other generated content is cached by a key, so a request for something already
generated is just a lookup with no LLM call.

Each section also gets a short multiple-choice mini-quiz, generated by reusing
``app.services.quiz.generate_quiz`` with the section's title as a topic filter — this reuses
the existing grounded generation, validation, persistence and grading pipeline (and the
frontend's quiz component) rather than inventing a parallel one.
"""

